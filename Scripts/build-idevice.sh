#!/bin/bash
# Build the idevice xcframework (MIT, github.com/jkcoxson/idevice) from source,
# with the patches in Patches/idevice applied.
#
# Built rather than fetched because iCTRL needs one function the release does
# not have: pairable_host_accept_unadvertised, on-device pairing without the
# library's own mDNS advertising (raw multicast, which an iOS app may only send
# with the multicast entitlement). The app publishes the Bonjour service itself.
#
# Needs Rust with the aarch64-apple-ios target:
#   rustup target add aarch64-apple-ios
# Only the iOS device slice is built, the only one the app ships.
set -euo pipefail

VERSION="${IDEVICE_VERSION:-v0.1.68}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="$ROOT/Frameworks/IDevice.xcframework"
PATCHES="$ROOT/Patches/idevice"
SRC="$ROOT/build/idevice-src"

# The stamp covers the version and every patch, so editing a patch rebuilds.
STAMP="$VERSION $(cat "$PATCHES"/*.patch | shasum -a 256 | cut -c1-16)"
if [ -f "$DEST/ios-arm64/libidevice_ffi.a" ] && [ "$(cat "$DEST/.version" 2>/dev/null)" = "$STAMP" ]; then
    echo "✅ IDevice.xcframework ${VERSION} (patched) already present"
    exit 0
fi

command -v cargo >/dev/null || { echo "❌ cargo not found — install Rust from https://rustup.rs"; exit 1; }
if command -v rustup >/dev/null && ! rustup target list --installed | grep -qx aarch64-apple-ios; then
    echo "❌ Rust target aarch64-apple-ios missing — rustup target add aarch64-apple-ios"
    exit 1
fi

# A clean checkout of the pinned tag every time the stamp changes: patches
# apply to pristine sources, and cargo's target/ survives for a fast rebuild.
if [ ! -d "$SRC/.git" ]; then
    echo "⬇️  Cloning idevice ${VERSION}…"
    git clone -q --depth 1 --branch "$VERSION" https://github.com/jkcoxson/idevice.git "$SRC"
else
    git -C "$SRC" fetch -q --depth 1 origin "refs/tags/$VERSION:refs/tags/$VERSION"
    git -C "$SRC" checkout -q --force "$VERSION"
    git -C "$SRC" clean -qfd -e target
fi
for p in "$PATCHES"/*.patch; do
    echo "🩹 $(basename "$p")"
    git -C "$SRC" apply "$p"
done

echo "🦀 Building libidevice_ffi for aarch64-apple-ios (several minutes the first time)…"
# Same flags as upstream's `just apple-build` for the device slice.
(cd "$SRC/ffi" && \
    BINDGEN_EXTRA_CLANG_ARGS="--sysroot=$(xcrun --sdk iphoneos --show-sdk-path)" \
    IPHONEOS_DEPLOYMENT_TARGET=17.0 \
    cargo build --release --target aarch64-apple-ios --features obfuscate)

# Same layout the release asset has: the static library plus Headers/ holding
# idevice.h (generated by the ffi build), plist.h and the Swift module map.
rm -rf "$DEST"
mkdir -p "$DEST/ios-arm64/Headers"
cp "$SRC/target/aarch64-apple-ios/release/libidevice_ffi.a" "$DEST/ios-arm64/"
cp -R "$SRC/swift/include/." "$DEST/ios-arm64/Headers/"
cp "$SRC/ffi/idevice.h" "$DEST/ios-arm64/Headers/idevice.h"

/usr/bin/python3 - "$DEST/Info.plist" <<'PY'
import plistlib, sys
plistlib.dump({
    "AvailableLibraries": [{
        "LibraryIdentifier": "ios-arm64",
        "LibraryPath": "libidevice_ffi.a",
        "HeadersPath": "Headers",
        "SupportedArchitectures": ["arm64"],
        "SupportedPlatform": "ios",
    }],
    "CFBundlePackageType": "XFWK",
    "XCFrameworkFormatVersion": "1.0",
}, open(sys.argv[1], "wb"))
PY

echo "$STAMP" > "$DEST/.version"
echo "✅ IDevice.xcframework ready ($(du -sh "$DEST" | cut -f1), iOS arm64, patched)"
